/**
 * One 3D model per catalogue choice that is a physical object: every spacecraft part
 * (src/data/parts.ts), every ground station (src/data/ground.ts) and every ride's launch
 * vehicle (src/data/rides.ts). Built by procedural generators in scripts/assets/models/parts/.
 *
 * Model id: `model.<catalogue id>`, e.g. `model.prop-ion`, `model.ground-dsn`, `model.ride-gto`.
 */

const PROCEDURAL = { source: 'procedural', license: 'Project original', ai: false } as const

const entry = <const Id extends string, const Group extends string>(id: Id, group: Group) =>
  ({
    id: `model.${id}`,
    kind: 'model',
    file: `models/parts/${id}.glb`,
    src: `parts/${id}.glb`,
    credit: `Generated by scripts/assets/models/parts/${group}.ts`,
    ...PROCEDURAL,
  }) as const

