import { CATALOGUE_MODELS, CATALOGUE_PORTRAITS } from './catalogueModels.ts'

/**
 * Asset manifest: the single list of every art and audio file the game ships.
 *
 * Game code refers to assets by `id` only (see `assetUrl`, `useModel`, `audio`).
 * Swapping a model or a track means replacing the file, never touching game code.
 *
 * Rules
 * - `file` is relative to `public/assets/` and must exist (checked by manifest.test.ts).
 * - Generated audio carries its `prompt`, so `pnpm assets:audio` can rebuild it.
 * - `ai: true` marks AI-generated content for the credits and the submission declaration.
 *
 * Model conventions (any source: procedural script, Blender, Meshy, Tripo, kit):
 * - 1 scene unit = 1 metre, +Y up, front faces +Z.
 * - Optional parts are nodes named `part_<partId>` using ids from src/data/parts.ts.
 *   The game shows the parts the player picked and hides the rest.
 * - Moving parts hang under `pivot_<name>` nodes placed on the hinge, so the game
 *   only rotates the pivot (e.g. `pivot_wing-left` for solar wing deployment).
 */

export type AssetSource =
  | 'procedural' // authored by a script in scripts/assets/models
  | 'elevenlabs'
  | 'meshy'
  | 'tripo'
  | 'kit' // third-party asset pack (Kenney, Quaternius, ...)
  | 'nasa'
  | 'team' // made by hand by a teammate

interface AssetBase {
  id: string
  /** Path under public/assets/ */
  file: string
  source: AssetSource
  license: string
  /** AI-generated content, declared in the credits */
  ai: boolean
  credit?: string
}

export interface ModelAsset extends AssetBase {
  kind: 'model'
  /** Raw source under assets-src/models/, optimized into `file` by `pnpm assets:models` */
  src: string
}

export interface AudioAsset extends AssetBase {
  kind: 'music' | 'sfx' | 'voice'
  /** Generation prompt (ElevenLabs), or the spoken line for voice */
  prompt?: string
  durationSec?: number
  loop?: boolean
  /** 0..1 gain relative to its group */
  volume?: number
  /** Subtitle shown while a voice line plays */
  caption?: string
  voiceId?: string
}

export interface ImageAsset extends AssetBase {
  kind: 'image' | 'texture'
  prompt?: string
}

export type Asset = ModelAsset | AudioAsset | ImageAsset

