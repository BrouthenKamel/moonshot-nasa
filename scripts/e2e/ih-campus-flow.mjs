import { chromium } from 'playwright-core'
// Ice Hunters smoke: setup → walk to Briefing → complete → back on campus. Usage: node scripts/e2e/ih-campus-flow.mjs <shotDir> (dev server on :5210)
const S = process.argv[2] ?? 'docs/design/shots'
const browser = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome',
  args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errs = []; page.on('pageerror', (e) => errs.push(e.message))
await page.goto('http://localhost:5210/')
await page.getByRole('button').first().click()
await page.waitForSelector('[data-testid="astronaut-setup"]', { timeout: 30000 })
await page.fill('input[placeholder="Your name"]', 'Kam')
await page.click('[data-testid="astronaut-begin"]')
await page.waitForTimeout(3000)
await page.screenshot({ path: S + '/campus-1.png' })
await page.click('[data-testid="door-briefing"]')
const t0 = Date.now()
await page.waitForSelector('[data-room="briefing"]', { timeout: 120000 })
console.log('walked into briefing in', Date.now() - t0, 'ms')
await page.click('[data-testid="room-complete"]')
await page.waitForSelector('[data-testid="campus"]')
await page.waitForTimeout(3000)
console.log('objective now:', await page.textContent('[data-testid="objective"]'))
await page.screenshot({ path: S + '/campus-2.png' })
console.log('page errors:', errs)
await browser.close()
